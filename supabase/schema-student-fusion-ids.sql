-- Fusion Check-In — adds a short, staff-facing "Fusion ID" (e.g. F0001) for every student, kept in
-- its own table rather than a column on students. Review this, then run it in the Supabase SQL
-- Editor.
--
-- Why it exists: student_number is now optional (schema-student-number-optional.sql), and the
-- printed pass's filename is built from the student's name — two students who share the same first
-- and last name, with neither one's real ID known yet, would otherwise be indistinguishable in a
-- staff member's downloads folder. The code itself has nothing to do with who the student is (name,
-- email, faculty, etc., already on students) — it's purely an internal admin reference, so it lives
-- in its own table rather than mixed into the student's real profile data.
--
-- Not shown to students, not printed on the pass card — see generatePassPdf.ts's passFileName().
--
-- Auto-generated by a trigger (not application code) so two students created at the same moment —
-- e.g. a 50-row CSV import — can never race onto the same code; a Postgres sequence is atomic even
-- under concurrent inserts.

create sequence if not exists public.fusion_id_seq;

create table if not exists public.student_fusion_ids (
  student_id uuid primary key references public.students(id) on delete cascade,
  fusion_code text not null unique,
  created_at timestamptz not null default now()
);

alter table public.student_fusion_ids enable row level security;
create policy "Authenticated staff can read student_fusion_ids" on public.student_fusion_ids for select to authenticated using (true);
create policy "Authenticated staff can insert student_fusion_ids" on public.student_fusion_ids for insert to authenticated with check (true);

create or replace function public.assign_fusion_id()
returns trigger
language plpgsql
as $$
begin
  insert into public.student_fusion_ids (student_id, fusion_code)
  values (new.id, 'F' || lpad(nextval('public.fusion_id_seq')::text, 4, '0'));
  return new;
end;
$$;

drop trigger if exists assign_fusion_id_trigger on public.students;
create trigger assign_fusion_id_trigger
  after insert on public.students
  for each row
  execute function public.assign_fusion_id();

-- Backfill every existing student, oldest first, so earlier signups get earlier codes.
insert into public.student_fusion_ids (student_id, fusion_code)
select id, 'F' || lpad(nextval('public.fusion_id_seq')::text, 4, '0')
from public.students
order by created_at
on conflict (student_id) do nothing;

-- Verify: students and codes should match (every student has exactly one, all unique).
select count(*) as students, count(distinct f.fusion_code) as codes
from public.students s
left join public.student_fusion_ids f on f.student_id = s.id;
